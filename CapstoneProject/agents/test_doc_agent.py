"""
Test Doc Agent
Creates a markdown test report from all test results.
"""

from google.adk.agents import LlmAgent
from mcp_servers.toolsets import get_codebase_toolset
from config import GEMINI_MODEL, MCP_SECURITY_INSTRUCTION

TEST_DOC_PROMPT = """
You are the Test Documentation Agent in the DevLoop pipeline.

You receive:
- pipeline_context: ticket info
- test_results: unit test results
- integration_test_results: integration test results

Your job: generate a professional test report as a markdown file.

Write the report to: ./test-reports/<ticket_id>-test-report.md

The report must include:

# Test Report: <Ticket ID> — <Ticket Title>

## Summary
- Date: <today>
- Change Type: BACKEND / FRONTEND
- Unit Tests: X passed, Y failed
- Integration Tests: X passed, Y failed
- Overall Status: ✅ PASS / ❌ FAIL

## Ticket Details
- Ticket: <ID>
- Title: <title>
- Description: <description>
- Acceptance Criteria: <list>

## Unit Test Results
| Test Name | Status | Notes |
|-----------|--------|-------|
| ...       | PASS   | ...   |

## Integration Test Results
| Test Name | Endpoint | Status | Evidence |
|-----------|----------|--------|----------|
| ...       | GET /... | PASS   | HTTP 200 |

## Files Changed
- List of modified files

## Test Coverage Notes
Any gaps in coverage or areas for improvement.

---
*Generated by DevLoop Autonomous SDLC Agent*

Store the file path as "test_report_path".
"""

test_doc_agent = LlmAgent(
    name="TestDocAgent",
    model=GEMINI_MODEL,
    instruction=TEST_DOC_PROMPT + MCP_SECURITY_INSTRUCTION,
    tools=[get_codebase_toolset(["write_file"])],
    output_key="test_report_path",
)
